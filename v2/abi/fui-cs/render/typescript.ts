import type { AbiFunction, AbiModule, ArrayElement, ParamProjection, ReturnProjection, Scalar } from "./model";

function scalarType(scalar: Scalar): string {
  if (scalar === "u64") return "bigint";
  if (scalar === "bool") return "boolean";
  return "number";
}

function arrayType(element: ArrayElement): string {
  switch (element) {
    case "f32": return "Float32Array";
    case "u32": return "Uint32Array";
    case "u8": return "Uint8Array";
  }
}

function arrayWriter(element: ArrayElement): string {
  switch (element) {
    case "f32": return "writeFloat32";
    case "u32": return "writeUint32";
    case "u8": return "writeBytes";
  }
}

function paramType(param: ParamProjection): string {
  switch (param.kind) {
    case "scalar": return scalarType(param.scalar);
    case "text": return "string";
    case "bytes": return "Uint8Array";
    case "array": return arrayType(param.element);
    case "out": return "never";
  }
}

function returnExpression(call: string, returns: ReturnProjection): string {
  switch (returns.scalar) {
    case "void": return `  ${call};`;
    case "bool": return `  return Boolean(${call});`;
    case "u64": return `  return BigInt(${call} as bigint | number);`;
    default: return `  return Number(${call});`;
  }
}

function emitFunction(fn: AbiFunction): string {
  const inputs = fn.params.filter((param) => param.kind !== "out");
  const outputs = fn.params.flatMap((param) => (param.kind === "out" ? [param.element] : []));
  const params = inputs.map((param) => `${param.name}: ${paramType(param)}`).join(", ");
  const writes: string[] = [];
  const args: string[] = [];
  let outIndex = 0;
  for (const param of fn.params) {
    switch (param.kind) {
      case "scalar":
        args.push(param.scalar === "bool" ? `${param.name} ? 1 : 0` : param.name);
        break;
      case "text":
        writes.push(`    const ${param.name}Bytes = memory.writeUtf8(${param.name});`);
        args.push(`${param.name}Bytes.ptr`, `${param.name}Bytes.len`);
        break;
      case "bytes":
        writes.push(`    const ${param.name}Bytes = memory.writeBytes(${param.name});`);
        args.push(`${param.name}Bytes.ptr`, `${param.name}Bytes.len`);
        break;
      case "array":
        args.push(`memory.${arrayWriter(param.element)}(${param.name}).ptr`);
        if (param.withLength === true) {
          args.push(`${param.name}.length`);
        }
        break;
      case "out":
        args.push(`outputs[${String(outIndex)}]`);
        outIndex += 1;
        break;
    }
  }
  const usesMemory = writes.length > 0 || fn.params.some((param) => param.kind === "array");
  if (outputs.length > 0) {
    const kinds = outputs.map((element) => `"${element}"`).join(", ");
    const body = [
      `  return callHarnessWithOutputs(MODULE, "${fn.abiName}", [${kinds}], (${usesMemory ? "memory" : "_memory"}, outputs) => {`,
      ...writes,
      `    return [${args.join(", ")}];`,
      "  });",
    ];
    return [`export function ${fn.abiName}(${params}): Float64Array {`, ...body, "}"].join("\n");
  }
  const lowering = usesMemory
    ? [`(memory) => {`, ...writes, `    return [${args.join(", ")}];`, "  }"].join("\n")
    : `() => [${args.join(", ")}]`;
  const call = `callHarness(MODULE, "${fn.abiName}", ${lowering})`;
  const resultType = fn.returns.scalar === "void" ? "void" : scalarType(fn.returns.scalar);
  return [`export function ${fn.abiName}(${params}): ${resultType} {`, returnExpression(call, fn.returns), "}"].join("\n");
}

export function emitShimModule(module: AbiModule, functions: readonly AbiFunction[]): string {
  const selected = functions.filter((fn) => fn.module === module);
  const header = [
    "// Generated by v2/abi/generate-fui-cs.ts (fui-cs-ffi). Do not edit by hand.",
    `// JSImport module \`${module}\`: lowers fui-cs value-level calls into the managed harness's pointer-level imports.`,
    "",
  ];
  if (selected.length === 0) return [...header, "export {};", ""].join("\n");
  const hasOutputs = (fn: AbiFunction): boolean => fn.params.some((param) => param.kind === "out");
  const usedHelpers = [
    ...(selected.some((fn) => !hasOutputs(fn)) ? ["callHarness"] : []),
    ...(selected.some(hasOutputs) ? ["callHarnessWithOutputs"] : []),
  ];
  return [
    ...header,
    `import { ${usedHelpers.join(", ")} } from "../../tier3-contract.ts";`,
    "",
    `const MODULE = "${module}";`,
    "",
    selected.map(emitFunction).join("\n\n"),
    "",
  ].join("\n");
}
